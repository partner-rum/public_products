// ============================================================
// ОБЕЗВРЕЖИВАНИЕ РАЗМЕТКИ В ДАННЫХ. Подключать ПОСЛЕ всех data/*.js.
//
// Витрина собирает HTML из данных конкатенацией строк, и до 03.09.2026 делала
// это БЕЗ экранирования: имя продукта, базовый актив, срок и прочие строковые
// поля уходили в innerHTML как есть. Значение поля «Срок» вида
// <img src=... onerror=...> исполнялось у каждого посетителя доски — проверено
// опытом, не предположение. Путь: заявка сейлза → одобрение в Telegram →
// коммит в data/ → выполнение в браузере клиента. CSP на сайте нет,
// второго рубежа обороны не существует.
//
// Класс закрыт ЗДЕСЬ, в одном месте, а не в 37 точках вставки на пяти
// страницах: пропустить одну точку — значит оставить дыру, и никакая
// аккуратность этого не гарантирует.
//
// Экранируем ТОЛЬКО угловые скобки. Кавычки и амперсанд не трогаем намеренно:
// они законны в данных («S&P 500 (SPY)»), а те же значения печатаются и через
// textContent, где &amp; показался бы как есть. Угловых скобок в данных витрины
// нет ни одной — проверено по всем файлам, так что на реальном контенте правка
// не видна. Отравленное значение станет видимым текстом, а не разметкой.
//
// Идемпотентно: после замены «<» в строке не остаётся, повторный проход
// ничего не меняет. Поэтому порядок подключения на странице не критичен.
// ============================================================
(function () {
  var MAX_DEPTH = 6;

  function harden(v, depth) {
    if (typeof v === "string") {
      return (v.indexOf("<") < 0 && v.indexOf(">") < 0) ? v
        : v.replace(/</g, "&lt;").replace(/>/g, "&gt;");
    }
    if (!v || typeof v !== "object" || depth > MAX_DEPTH) return v;
    if (Array.isArray(v)) {
      for (var i = 0; i < v.length; i++) v[i] = harden(v[i], depth + 1);
      return v;
    }
    for (var k in v) {
      if (Object.prototype.hasOwnProperty.call(v, k)) v[k] = harden(v[k], depth + 1);
    }
    return v;
  }

  // Все глобали данных витрины. Лишние имена безвредны — отсутствующие
  // пропускаются; забытое имя, наоборот, оставило бы страницу без защиты.
  var GLOBALS = ["SITE_DATA", "PLACEMENTS_DATA", "PLACEMENT_DOCS", "OFFERINGS",
                 "DIGEST_ARCHIVE", "DIGEST", "RESEARCH", "MORNING", "EVENTS",
                 "IDEAS", "RATES"];
  for (var g = 0; g < GLOBALS.length; g++) {
    var name = GLOBALS[g];
    try { if (window[name]) window[name] = harden(window[name], 0); } catch (e) {}
  }
})();
